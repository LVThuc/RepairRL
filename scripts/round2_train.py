"""Dev-selected DPO-hard / GRPO with saved intermediate adapters and early stopping."""
import argparse
import importlib.metadata
import json
from pathlib import Path
import random
import statistics
import time
from repairrl.common import load_config, messages, read_jsonl, digest


def atomic_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(value, indent=2))
    temporary.replace(path)


def hard_rows(source, bank):
    manifest = json.loads((bank / "manifest.json").read_text())
    if manifest["source_sha256"] != digest("data/prepared/scale-verified/train.jsonl"):
        raise ValueError("Hard negatives came from a different source manifest")
    if manifest["adapter_sha256"] != digest("checkpoints/M1/adapter_model.safetensors"):
        raise ValueError("Hard negatives were not generated by this M1")
    if manifest["tests_sha256"] != digest("data/prepared/scale-verified/tests.json"):
        raise ValueError("Hard-negative test suites changed")
    progress = json.loads((bank / "status.json").read_text())
    if progress["state"] != "completed":
        raise ValueError("Rollout bank must finish before starting an immutable DPO trial")
    lookup = {str(r["id"]): r for r in source}
    records = {str(r["id"]): r for r in read_jsonl(bank / "rollouts.jsonl")}
    result = []
    from scripts.round2_rollouts import select_negative
    from agent.repair_v2 import fingerprint
    for pair in read_jsonl(bank / "pairs.jsonl"):
        rid = str(pair["id"])
        row, record = lookup[rid], records[rid]
        if not record["gold_grade"] or not record["gold_grade"]["success"]:
            raise ValueError("Unverified chosen response")
        allowed = {fingerprint(s["generation"]["text"]) for s in select_negative(row, record["samples"])}
        if fingerprint(pair["rejected_code"]) not in allowed or str(pair["problem_id"]) != str(row["problem_id"]):
            raise ValueError("Rejected response lacks verified same-prompt provenance")
        result.append(row | {"rejected_code": pair["rejected_code"], "sample_index": pair["sample_index"]})
    if len(result) < 128:
        raise ValueError(f"Only {len(result)} verified hard pairs: inspect before optimizing")
    return result


def format_dataset(rows, tokenizer, kind):
    from datasets import Dataset
    formatted = []
    kept = []
    for row in rows:
        prompt = tokenizer.apply_chat_template(messages(row["statement"], row["buggy_code"]),
                                                tokenize=False, add_generation_prompt=True)
        length = len(tokenizer(prompt, add_special_tokens=False)["input_ids"])
        if kind == "grpo":
            if length <= 1536:
                formatted.append({"prompt": prompt, "problem_id": str(row["problem_id"]), "row_id": str(row["id"])})
                kept.append(row["id"])
        else:
            chosen, rejected = row["fixed_code"] + tokenizer.eos_token, row["rejected_code"] + tokenizer.eos_token
            if max(len(tokenizer(prompt + c, add_special_tokens=False)["input_ids"]) for c in (chosen, rejected)) <= 2048:
                formatted.append({"prompt": prompt, "chosen": chosen, "rejected": rejected})
                kept.append(row["id"])
    if len(formatted) < 128:
        raise ValueError("Too few context-fitting rows")
    return Dataset.from_list(formatted), kept


def variance_probe(model, tokenizer, rows, output, variant):
    import torch
    from transformers import set_seed
    from evaluation.reward_v2 import dense_reward
    from evaluation.grading_service import GradingClient
    grader = GradingClient()
    selected = list({str(r["problem_id"]): r for r in rows}.values())
    random.Random(12345).shuffle(selected)
    groups = []
    model.eval()
    with (output / "variance-rollouts.jsonl").open("w") as log:
        for row in selected[:30]:
            set_seed(42 + len(groups))
            prompt = messages(row["statement"], row["buggy_code"])
            inputs = tokenizer.apply_chat_template(prompt, tokenize=True, add_generation_prompt=True,
                                                   return_tensors="pt", return_dict=True).to(model.device)
            with torch.inference_mode():
                sampled = model.generate(**inputs, num_return_sequences=4, do_sample=True, temperature=0.8,
                                         top_p=0.95, top_k=50, repetition_penalty=1.1, max_new_tokens=768,
                                         pad_token_id=tokenizer.pad_token_id, use_cache=True)
            texts = tokenizer.batch_decode(sampled[:, inputs["input_ids"].shape[-1]:], skip_special_tokens=True)
            grades = grader.batch([(text, row["problem_id"]) for text in texts])
            rewards = [dense_reward(g, variant) for g in grades]
            group = {"row_id": row["id"], "problem_id": row["problem_id"], "rewards": rewards,
                     "variance": statistics.pvariance(rewards)}
            groups.append(group)
            for text, grade, reward in zip(texts, grades, rewards, strict=True):
                log.write(json.dumps({"id": row["id"], "completion": text, "grade": grade.to_dict(), "reward": reward}) + "\n")
            log.flush()
            print("Variance", len(groups), rewards, flush=True)
    fraction = sum(g["variance"] > 1e-12 for g in groups) / len(groups)
    report = {"passed": fraction >= .2, "mixed_group_fraction": fraction, "groups": groups,
              "reward_version": variant, "source_sha256": digest("data/prepared/scale-verified/train.jsonl"),
              "parent_sha256": digest("checkpoints/M1-merged/repairrl-merge.json")}
    atomic_json(output / "variance.json", report)
    if not report["passed"]:
        raise ValueError("Variance gate failed: inspect training task difficulty/reward before RL")
    model.train()


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--kind", choices=["dpo", "grpo"], required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--bank", type=Path, default=Path("results/round2/rollouts"))
    p.add_argument("--learning-rate", type=float, default=5e-6)
    p.add_argument("--beta", type=float)
    p.add_argument("--epochs", type=float, default=3)
    p.add_argument("--max-steps", type=int, default=2000)
    p.add_argument("--interval", type=int, default=200)
    p.add_argument("--dev-tasks", type=int, default=60)
    p.add_argument("--reward", choices=["dense", "correctness"], default="dense")
    p.add_argument("--resume", action="store_true")
    p.add_argument("--full-precision", action="store_true")
    p.add_argument("--rpo-alpha", type=float)
    a = p.parse_args()
    if a.output.exists() and not a.resume:
        p.error("Output exists; choose a new experiment directory")
    a.output.mkdir(parents=True, exist_ok=True)
    from training.common import check_data, setup_model, lora_config
    cfg = load_config("configs/full-grpo.yaml" if a.kind == "grpo" else "configs/full-dpo.yaml")
    rows, _ = check_data(cfg)
    if a.kind == "dpo":
        rows = hard_rows(rows, a.bank)
    import torch
    torch.set_num_threads(4)
    if a.full_precision:
        cfg["load_in_4bit"] = False
    model, tokenizer = setup_model(cfg)
    dataset, kept = format_dataset(rows, tokenizer, a.kind)
    metadata = {"kind": a.kind, "settings": vars(a) | {"output": str(a.output), "bank": str(a.bank)},
                "parent_sha256": digest("checkpoints/M1-merged/repairrl-merge.json"),
                "training_row_ids": kept, "training_rows": len(dataset),
                "train_sha256": digest(cfg["train_data"]), "dev_sha256": digest(cfg["dev_data"]),
                "tests_sha256": digest(cfg["tests"]), "reward_sha256": digest("evaluation/reward_v2.py"),
                "trainer_sha256": digest(__file__), "packages": {k: importlib.metadata.version(k)
                    for k in ("torch", "trl", "transformers", "peft", "bitsandbytes", "datasets")}}
    if a.kind == "dpo":
        metadata["pairs_sha256"] = digest(a.bank / "pairs.jsonl")
    atomic_json(a.output / "experiment.json", metadata)
    from evaluation.round2 import dev_rows, attached_generator, evaluate
    from transformers import TrainerCallback
    tasks = dev_rows(a.dev_tasks)
    atomic_json(a.output / "dev-ids.json", [r["id"] for r in tasks])

    class Monitor(TrainerCallback):
        def __init__(self):
            self.records = read_jsonl(a.output / "dev-history.jsonl") if (a.output / "dev-history.jsonl").exists() else []
            self.trainer = None

        def score(self, state, model):
            if any(r["step"] == state.global_step for r in self.records):
                return
            was_training = model.training
            model.eval()
            start = time.monotonic()
            metrics = evaluate(tasks, attached_generator(model, tokenizer), "single")
            model.train(was_training)
            record = {"step": state.global_step, "epoch": state.epoch, "metrics": metrics,
                      "seconds": time.monotonic() - start}
            snapshot = a.output / "snapshots" / f"step-{state.global_step}"
            snapshot.mkdir(parents=True, exist_ok=True)
            model.save_pretrained(snapshot)
            tokenizer.save_pretrained(snapshot)
            atomic_json(snapshot / "round2-checkpoint.json", metadata | {"dev": record})
            record["adapter"] = str(snapshot)
            self.records.append(record)
            with (a.output / "dev-history.jsonl").open("a") as log:
                log.write(json.dumps(record) + "\n")
            trained = [r for r in self.records if r["step"] > 0]
            best = max(trained or self.records, key=lambda r: (r["metrics"]["pass@1"], r["metrics"]["partial_fraction"], -r["step"]))
            baseline = self.records[0]
            atomic_json(a.output / "selection.json", {"selected": best, "baseline": baseline,
                "improved_over_parent": best["metrics"]["pass@1"] > baseline["metrics"]["pass@1"],
                "criterion": "dev pass@1, then partial fraction, then earlier step; never held-out",
                "state": "training", "steps": state.global_step})
            print("DEV", json.dumps(record), flush=True)

        def on_train_begin(self, args, state, control, model=None, **kwargs):
            self.score(state, model)

        def on_save(self, args, state, control, model=None, **kwargs):
            self.score(state, model)
            candidates = [r for r in self.records if r["step"] > 0]
            if candidates:
                best = max(candidates, key=lambda r: (r["metrics"]["pass@1"], r["metrics"]["partial_fraction"], -r["step"]))
                # At least 800 RL updates before a flat dev curve can stop training.
                if a.kind == "grpo" and state.global_step >= 800 and state.global_step - best["step"] >= 600:
                    control.should_training_stop = True
                    print("Early stop: three dev intervals without improvement", flush=True)
            return control

    import torch
    torch.set_num_threads(4)
    from trl import GRPOConfig, GRPOTrainer, DPOConfig
    from scripts.train_dpo_cached import CachedDPOTrainer
    interval = a.interval if a.kind == "grpo" else max(1, (len(dataset) + 7) // 8 // 2)
    shared = dict(output_dir=str(a.output), seed=42, data_seed=42, per_device_train_batch_size=1,
                  per_device_eval_batch_size=1, gradient_accumulation_steps=4 if a.kind == "grpo" else 8,
                  learning_rate=a.learning_rate, fp16=True, bf16=False, gradient_checkpointing=True,
                  gradient_checkpointing_kwargs={"use_reentrant": False}, logging_steps=5,
                  save_steps=interval, save_total_limit=3, report_to="none", optim="adamw_torch",
                  eval_strategy="no", warmup_ratio=0.03)
    monitor = Monitor()
    if a.kind == "grpo":
        if not (a.output / "variance.json").exists():
            variance_probe(model, tokenizer, rows, a.output, a.reward)
        gate = json.loads((a.output / "variance.json").read_text())
        if not gate["passed"] or gate["reward_version"] != a.reward or gate["source_sha256"] != digest(cfg["train_data"]):
            raise ValueError("Failed or stale variance gate; do not resume into training")
        if gate["parent_sha256"] != metadata["parent_sha256"]:
            raise ValueError("Variance parent changed")
        from evaluation.reward_v2 import RemoteExecutionReward
        trainer = GRPOTrainer(model=model, args=GRPOConfig(**shared, max_steps=a.max_steps,
            num_generations=4, max_prompt_length=1536, max_completion_length=768,
            beta=a.beta if a.beta is not None else .04, temperature=.8, top_p=.95, top_k=50,
            repetition_penalty=1.1, use_vllm=False, remove_unused_columns=False,
            mask_truncated_completions=True, loss_type="dapo"), train_dataset=dataset,
            processing_class=tokenizer, peft_config=lora_config(cfg), callbacks=[monitor],
            reward_funcs=RemoteExecutionReward(a.output / "rewards.jsonl", a.reward))
    else:
        trainer = CachedDPOTrainer(model=model, ref_model=None, args=DPOConfig(**shared,
            num_train_epochs=a.epochs, beta=a.beta if a.beta is not None else .1,
            max_length=2048, max_prompt_length=None, max_completion_length=None,
            precompute_ref_log_probs=True, rpo_alpha=a.rpo_alpha), train_dataset=dataset, processing_class=tokenizer,
            peft_config=lora_config(cfg), callbacks=[monitor])
    monitor.trainer = trainer
    from transformers.trainer_utils import get_last_checkpoint
    resume = get_last_checkpoint(str(a.output)) if a.resume else None
    started = time.monotonic()
    result = trainer.train(resume_from_checkpoint=resume)
    monitor.score(trainer.state, trainer.model)
    trainer.save_model(str(a.output / "final"))
    tokenizer.save_pretrained(a.output / "final")
    selection = json.loads((a.output / "selection.json").read_text())
    selection.update(state="completed", training_seconds=time.monotonic() - started,
                     peak_allocated_gb=torch.cuda.max_memory_allocated()/1e9, train_metrics=result.metrics)
    atomic_json(a.output / "selection.json", selection)
    print("COMPLETED", json.dumps(selection), flush=True)


if __name__ == "__main__":
    main()
